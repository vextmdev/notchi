import AppKit

@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var items: [ClipboardItem] = [] {
        didSet { scheduleSave() }
    }

    private let pasteboard = NSPasteboard.general
    private let store = ClipboardStore()
    private var lastChangeCount: Int
    private var timer: Timer?
    private var pendingSave: Task<Void, Never>?

    private var remembersHistory: Bool {
        UserDefaults.standard.bool(forKey: Preferences.clipboardRemember)
    }

    private var maxUnpinnedItems: Int {
        UserDefaults.standard.integer(forKey: Preferences.clipboardLimit)
    }

    // password managers mark secrets with these (nspasteboard.org)
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        // load here and not in init, the defaults aren't registered yet at that point
        if remembersHistory {
            items = store.load()
            trim()
        }

        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.checkForChanges() }
        }
    }

    // MARK: - Reading

    private func checkForChanges() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard UserDefaults.standard.bool(forKey: Preferences.clipboardEnabled) else { return }

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            insert(.text(text))
        } else if let image = NSImage(pasteboard: pasteboard) {
            insert(.image(image))
        }
    }

    private func insert(_ content: ClipboardItem.Content) {
        if case .text(let text) = content,
           let index = items.firstIndex(where: { $0.text == text }) {
            var existing = items.remove(at: index)
            existing.date = Date()
            items.insert(existing, at: 0)
            return
        }

        items.insert(ClipboardItem(content: content, date: Date()), at: 0)
        trim()
    }

    private func trim() {
        var unpinnedCount = 0
        items = items.filter { item in
            if item.isPinned { return true }
            unpinnedCount += 1
            return unpinnedCount <= maxUnpinnedItems
        }
    }

    // MARK: - Saving

    // batch quick changes (pinning a few things, copying fast) into one write
    private func scheduleSave() {
        pendingSave?.cancel()
        pendingSave = Task { [weak self] in
            try? await Task.sleep(for: .seconds(1))
            guard !Task.isCancelled else { return }
            self?.saveNow()
        }
    }

    func saveNow(wait: Bool = false) {
        pendingSave?.cancel()
        pendingSave = nil
        if remembersHistory {
            store.save(items, wait: wait)
        } else {
            store.clear()
        }
    }

    // MARK: - Actions

    func copy(_ item: ClipboardItem) {
        pasteboard.clearContents()
        switch item.content {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image(let image):
            pasteboard.writeObjects([image])
        }
        // remember the change count so this copy doesn't show up as a new item.
        // the item stays where it is, moving it made the whole row jump around
        lastChangeCount = pasteboard.changeCount
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].isPinned.toggle()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
    }

    func clearUnpinned() {
        items.removeAll { !$0.isPinned }
    }
}
